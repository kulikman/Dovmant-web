import { writeFileSync } from "node:fs";
import { images } from "../content/images";

const rows = Object.entries(images).map(
  ([id, d]) => `| \`${id}\` | ${d.page} | ${d.aspect} | ${d.framing} | ${d.description} |`,
);

const md = `# Shot list

Generated by \`npm run shot-list\` from \`content/images.ts\`. Do not edit by hand.

All images are delivered **black & white** (the site applies \`grayscale(1)\` anyway). Colour comes only from the red overlay block added in code.
Only the **real Dovmant device** may appear. No stock or AI-generated exoskeletons.

File location: \`/public/images/<slot-id>.webp\` (or \`.jpg\`), then set \`src\` in \`content/images.ts\`.

Until a real file exists, each slot shows generated stand-in artwork from \`/public/images/art/<slot-id>.svg\`
(\`npm run art\`). That artwork is deliberately abstract — motion studies, schematics, halftones — and depicts
neither the device nor any real person or organisation. Setting \`src\` replaces it.
Deliver at least 2× the displayed size (e.g. 2400 px on the long edge for hero frames).

| Slot id | Page | Aspect | Framing | Description |
| --- | --- | --- | --- | --- |
${rows.join("\n")}

## Video
| File | Spec |
| --- | --- |
| \`/public/video/hero.webm\`, \`/public/video/hero.mp4\` | B&W exoskeleton loop, 8–12 s, no audio, ≤ 3 MB, 4:5 |
| \`/public/video/hero-vertical.webm\`, \`.mp4\` | Vertical 9:16 variant for mobile |
| \`/public/video/film.mp4\` | Full film for the modal |
`;
writeFileSync("docs/shot-list.md", md);
console.log("docs/shot-list.md written");
